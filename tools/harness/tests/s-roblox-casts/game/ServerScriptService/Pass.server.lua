local MPS = game:GetService("MarketplaceService")
local function try(name, f)
	local ok, e = pcall(f)
	print(name, ok, if ok then "" else e)
end
game:GetService("Players").PlayerAdded:Connect(function(player)
	try("prompt", function() MPS:PromptGamePassPurchase(player.UserId, 1) end)
	try("rank", function() player:GetRankInGroup("abc") end)
	try("badge", function() game:GetService("BadgeService"):UserHasBadgeAsync(player, 1) end)
	try("owns-ok", function() MPS:UserOwnsGamePassAsync(player.UserId, 1) end)
	-- the classic bug: the Player instead of player.UserId (uncaught)
	local owns = MPS:UserOwnsGamePassAsync(player, 123456)
	print("owns", owns)
end)
